/**
 * Call Controller — Chatrio
 *
 * All handlers assume the `authenticate` preHandler has already run and
 * request.currentUser is populated.
 *
 * Authorization is re-validated independently on every sensitive operation —
 * being in a Socket.IO room is NOT treated as proof of authorization.
 */

import type { FastifyRequest, FastifyReply } from 'fastify';
import { z } from 'zod';
import { prisma } from '../config/prisma.js';
import { CallStatus, CallType } from '../types/database.js';
import {
  authorizeDirectCall,
  getCallForParticipant,
  assertValidTransition,
  generateLiveKitToken,
  isLiveKitConfigured,
  scheduleRingTimeout,
  clearRingTimeout,
  notifyIncomingCall,
} from '../services/call.service.js';
import { getIO } from '../sockets/index.js';

// ─────────────────────────────────────────────────────────────────────────────
// Validation schemas
// ─────────────────────────────────────────────────────────────────────────────

const initiateSchema = z.object({
  conversationId: z.string().uuid(),
  callType: z.enum(['AUDIO', 'VIDEO']).default('AUDIO'),
});

const callIdParamSchema = z.object({
  callId: z.string().uuid(),
});

const historyQuerySchema = z.object({
  limit:  z.coerce.number().int().min(1).max(50).default(20),
  before: z.string().datetime().optional(),
});

// ─────────────────────────────────────────────────────────────────────────────
// Shared error handler
// ─────────────────────────────────────────────────────────────────────────────

function handleError(err: unknown, reply: FastifyReply) {
  const e = err as any;
  const status: number = typeof e.statusCode === 'number' ? e.statusCode : 500;
  const message: string = e.message || 'Internal server error';
  console.error(`[Call] Error (${status}):`, message);
  return reply.status(status).send({ error: message });
}

// ─────────────────────────────────────────────────────────────────────────────
// POST /calls/initiate
// ─────────────────────────────────────────────────────────────────────────────

export async function initiateCallHandler(
  request: FastifyRequest,
  reply: FastifyReply,
) {
  const user = request.currentUser!;

  const parsed = initiateSchema.safeParse(request.body);
  if (!parsed.success) {
    return reply.status(400).send({ error: parsed.error.errors[0]?.message || 'Validation error' });
  }

  const { conversationId, callType } = parsed.data;

  try {
    if (!isLiveKitConfigured()) {
      return reply.status(503).send({
        error: 'Calling is not available. LiveKit is not configured on the server.',
      });
    }

    // 1. Self-call guard
    // 2. Authorization: DIRECT conversation, authenticated user is a member
    const { callerId, recipientId } = await authorizeDirectCall(conversationId, user.id);

    if (callerId === recipientId) {
      return reply.status(400).send({ error: 'Cannot call yourself' });
    }

    // 3. Prevent duplicate active outgoing call (caller already in a RINGING/ACTIVE call)
    const existingCall = await prisma.call.findFirst({
      where: {
        callerId,
        status: { in: ['RINGING', 'ACTIVE'] },
      },
    });

    if (existingCall) {
      return reply.status(409).send({
        error: 'You already have an active call',
        callId: existingCall.id,
      });
    }

    // 4. Check if recipient is already busy (RINGING or ACTIVE as either side)
    const recipientBusy = await prisma.call.findFirst({
      where: {
        OR: [
          { callerId: recipientId, status: { in: ['RINGING', 'ACTIVE'] } },
          { recipientId, status: { in: ['RINGING', 'ACTIVE'] } },
        ],
      },
    });

    if (recipientBusy) {
      return reply.status(409).send({ error: 'Recipient is busy' });
    }

    // 5. Create call record — room name = call UUID (generated by Prisma default)
    const call = await prisma.call.create({
      data: {
        conversationId,
        callerId,
        recipientId,
        callType,
        status: CallStatus.RINGING,
        livekitRoom: '', // temporary; updated immediately below with the real id
      },
      include: {
        caller:    { select: { id: true, displayName: true, avatarUrl: true } },
        recipient: { select: { id: true, displayName: true, avatarUrl: true } },
      },
    });

    // Use the call's own UUID as the LiveKit room name (set livekitRoom = id)
    const updatedCall = await prisma.call.update({
      where: { id: call.id },
      data: { livekitRoom: call.id },
      include: {
        caller:    { select: { id: true, displayName: true, avatarUrl: true } },
        recipient: { select: { id: true, displayName: true, avatarUrl: true } },
      },
    });

    // 6. Schedule ring timeout (45 s → MISSED)
    const io = getIO();
    scheduleRingTimeout(updatedCall.id, (callId) => {
      if (!io) return;
      // Notify both participants of timeout
      io.to(`user:${callerId}`).emit('call:timeout', { callId });
      io.to(`user:${recipientId}`).emit('call:timeout', { callId });
    });

    // 7. Notify recipient via Socket.IO (foreground/background reconnect path)
    if (io) {
      io.to(`user:${recipientId}`).emit('call:incoming', {
        callId: updatedCall.id,
        callType,
        conversationId,
        caller: updatedCall.caller,
      });
    }

    // 8. Push notification for backgrounded/terminated recipient
    await notifyIncomingCall({
      callId: updatedCall.id,
      recipientId,
      callerName: user.displayName,
      callType,
      conversationId,
    });

    return reply.status(201).send({
      callId: updatedCall.id,
      callType,
      status: updatedCall.status,
      conversationId,
      recipient: updatedCall.recipient,
    });
  } catch (err) {
    return handleError(err, reply);
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// POST /calls/:callId/token
// Issue a LiveKit token to an authorized participant
// ─────────────────────────────────────────────────────────────────────────────

export async function getCallTokenHandler(
  request: FastifyRequest,
  reply: FastifyReply,
) {
  const user = request.currentUser!;

  const paramsParsed = callIdParamSchema.safeParse(request.params);
  if (!paramsParsed.success) {
    return reply.status(400).send({ error: 'Invalid call ID' });
  }

  try {
    const call = await getCallForParticipant(paramsParsed.data.callId, user.id);

    // Only issue tokens for RINGING or ACTIVE calls
    if (call.status !== CallStatus.RINGING && call.status !== CallStatus.ACTIVE) {
      return reply.status(409).send({
        error: `Cannot join call in status: ${call.status}`,
      });
    }

    const { token, serverUrl } = await generateLiveKitToken(
      user.id,
      user.displayName,
      call.livekitRoom,
    );

    return reply.send({ token, serverUrl, roomName: call.livekitRoom });
  } catch (err) {
    return handleError(err, reply);
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// POST /calls/:callId/accept
// ─────────────────────────────────────────────────────────────────────────────

export async function acceptCallHandler(
  request: FastifyRequest,
  reply: FastifyReply,
) {
  const user = request.currentUser!;

  const paramsParsed = callIdParamSchema.safeParse(request.params);
  if (!paramsParsed.success) {
    return reply.status(400).send({ error: 'Invalid call ID' });
  }

  try {
    const call = await getCallForParticipant(paramsParsed.data.callId, user.id);

    // Only the recipient may accept
    if (call.recipientId !== user.id) {
      return reply.status(403).send({ error: 'Only the recipient can accept this call' });
    }

    assertValidTransition(call.status, CallStatus.ACTIVE);

    clearRingTimeout(call.id);

    const updated = await prisma.call.update({
      where: { id: call.id },
      data: { status: CallStatus.ACTIVE, startedAt: new Date() },
    });

    // Notify caller
    const io = getIO();
    if (io) {
      io.to(`user:${call.callerId}`).emit('call:accepted', {
        callId: call.id,
        callType: call.callType,
        conversationId: call.conversationId,
      });
    }

    return reply.send({ callId: updated.id, status: updated.status });
  } catch (err) {
    return handleError(err, reply);
  }
}

