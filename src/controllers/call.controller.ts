// ─────────────────────────────────────────────────────────────────────────────
// POST /calls/:callId/end
// Either participant may end an ACTIVE call
// ─────────────────────────────────────────────────────────────────────────────

export async function endCallHandler(
  request: FastifyRequest,
  reply: FastifyReply,
) {
  const user = request.currentUser!;

  const paramsParsed = callIdParamSchema.safeParse(request.params);
  if (!paramsParsed.success) {
    return reply.status(400).send({ error: 'Invalid call ID' });
  }

  try {
    const call = await getCallForParticipant(paramsParsed.data.callId, user.id);

    assertValidTransition(call.status, CallStatus.ENDED);
    clearRingTimeout(call.id);

    const endedAt = new Date();
    const duration = call.startedAt
      ? Math.round((endedAt.getTime() - call.startedAt.getTime()) / 1000)
      : null;

    const updated = await prisma.call.update({
      where: { id: call.id },
      data: { status: CallStatus.ENDED, endedAt, duration },
    });

    const io = getIO();
    if (io) {
      const payload = { callId: call.id, endedBy: user.id, duration };
      io.to(`user:${call.callerId}`).emit('call:ended', payload);
      io.to(`user:${call.recipientId}`).emit('call:ended', payload);
    }

    return reply.send({
      callId: updated.id,
      status: updated.status,
      duration: updated.duration,
    });
  } catch (err) {
    return handleError(err, reply);
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// GET /conversations/:id/calls  (call history for a direct conversation)
// ─────────────────────────────────────────────────────────────────────────────

export async function getCallHistoryHandler(
  request: FastifyRequest,
  reply: FastifyReply,
) {
  const user = request.currentUser!;
  const { id: conversationId } = request.params as { id: string };

  const queryParsed = historyQuerySchema.safeParse(request.query);
  if (!queryParsed.success) {
    return reply.status(400).send({ error: 'Invalid query parameters' });
  }

  const { limit, before } = queryParsed.data;

  try {
    // Verify membership
    const member = await prisma.conversationMember.findUnique({
      where: { conversationId_userId: { conversationId, userId: user.id } },
    });

    if (!member || !member.isActive) {
      return reply.status(403).send({ error: 'Not a member of this conversation' });
    }

    const calls = await prisma.call.findMany({
      where: {
        conversationId,
        ...(before ? { createdAt: { lt: new Date(before) } } : {}),
      },
      orderBy: { createdAt: 'desc' },
      take: limit,
      include: {
        caller:    { select: { id: true, displayName: true, avatarUrl: true } },
        recipient: { select: { id: true, displayName: true, avatarUrl: true } },
      },
    });

    return reply.send(calls);
  } catch (err) {
    return handleError(err, reply);
  }
}

